#!/usr/bin/env bash
# Create two throwaway loopback "disks" for safely testing RescueClone.
#   loopA = source  (512 MiB, GPT, one ext4 partition with some files)
#   loopB = dest    (768 MiB, blank)
# Records the device names in _testdisks.env so the other scripts can refuse to
# touch anything else.
set -euo pipefail

if [[ "$(uname -s)" != "Linux" ]]; then
  echo "This harness only runs on Linux." >&2
  exit 1
fi
if [[ "$(id -u)" != "0" ]]; then
  echo "Run as root (sudo)." >&2
  exit 1
fi

HERE="$(cd "$(dirname "$0")/.." && pwd)"
WORK="$HERE/_testdisks"
ENV_FILE="$HERE/_testdisks.env"
mkdir -p "$WORK"

SRC_IMG="$WORK/src.img"
DST_IMG="$WORK/dst.img"

echo "==> Creating backing files"
truncate -s 512M "$SRC_IMG"
truncate -s 768M "$DST_IMG"

LOOP_SRC="$(losetup --find --show "$SRC_IMG")"
LOOP_DST="$(losetup --find --show "$DST_IMG")"
echo "    source = $LOOP_SRC"
echo "    dest   = $LOOP_DST"

echo "==> Partitioning + formatting source ($LOOP_SRC)"
sgdisk --zap-all "$LOOP_SRC" >/dev/null 2>&1 || true
# single partition spanning most of the disk
sgdisk --new=1:2048:0 --typecode=1:8300 --change-name=1:"testdata" "$LOOP_SRC" >/dev/null
partprobe "$LOOP_SRC" || true
sleep 1
SRC_P1="${LOOP_SRC}p1"
[[ -b "$SRC_P1" ]] || SRC_P1="${LOOP_SRC}1"
mkfs.ext4 -q -L testdata "$SRC_P1"

echo "==> Writing sample files into source partition"
MNT="$(mktemp -d)"
mount "$SRC_P1" "$MNT"
echo "hello from rescueclone test $(date -u +%FT%TZ)" > "$MNT/hello.txt"
head -c 20000000 /dev/urandom > "$MNT/random.bin"   # ~20 MB of real data
sha256sum "$MNT"/*.* > "$HERE/_testdisks/source-checksums.txt" || true
sync
umount "$MNT"
rmdir "$MNT"

cat > "$ENV_FILE" <<EOF
# Generated by make-test-disks.sh — the integration scripts only act on these.
RC_TEST_SRC=$LOOP_SRC
RC_TEST_DST=$LOOP_DST
RC_TEST_SRC_IMG=$SRC_IMG
RC_TEST_DST_IMG=$DST_IMG
EOF

echo "==> Wrote $ENV_FILE"
echo "Done. Source=$LOOP_SRC  Dest=$LOOP_DST"
